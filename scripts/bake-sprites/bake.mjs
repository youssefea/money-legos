// npm run bake-sprites — renders every Lego from the board's own 3D rig (same studio, materials,
// lens and camera direction) to a transparent WebP at 2x in public/sprites/<legoId>.webp, and writes
// the pixel sizes to src/components/bricks/sprites.ts so <BrickSprite> reserves its box (no layout shift).
// Uses Playwright's bundled Chromium with real GPU flags. ONLY=<id> bakes one sprite.
import { chromium } from "playwright";
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { serve, GPU_ARGS } from "./serve.mjs";

const repo = fileURLToPath(new URL("../..", import.meta.url));
const outDir = path.join(repo, "public/sprites");
const DPR = 2;
// CSS px of the bake viewport per brick footprint; the files are DPR x this.
const BOX = { "4x2": [240, 180], "2x2": [150, 142] };

// Read the lego list (id + size) from the source so the script never drifts from src/lib/legos.ts.
const src = fs.readFileSync(path.join(repo, "src/lib/legos.ts"), "utf8");
const ids = [...src.matchAll(/^\s{4}id: "([a-z0-9-]+)",\s*\n\s{4}tier: "(featured|secondary)"/gm)].map((m) => ({ id: m[1], hero: m[2] === "featured" }));
if (ids.length !== 13) throw new Error(`expected 13 legos in src/lib/legos.ts, found ${ids.length}`);

fs.mkdirSync(outDir, { recursive: true });
const only = process.env.ONLY;
const s = await serve();
const browser = await chromium.launch({ args: GPU_ARGS });
const sizes = {};
let total = 0;
try {
  for (const { id, hero } of ids) {
    const [w, h] = BOX[hero ? "4x2" : "2x2"];
    sizes[id] = [w * DPR, h * DPR];
    if (only && only !== id) continue;
    const page = await browser.newPage({ viewport: { width: w, height: h }, deviceScaleFactor: DPR });
    page.on("pageerror", (e) => console.error(id, "pageerror", e.message));
    await page.goto(`${s.url}?bake=${id}`);
    await page.waitForFunction(() => window.__bakeReady === true, null, { timeout: 60000 });
    const renderer = await page.evaluate(() => {
      const gl = document.querySelector("canvas")?.getContext("webgl2");
      const ext = gl?.getExtension("WEBGL_debug_renderer_info");
      return ext ? gl.getParameter(ext.UNMASKED_RENDERER_WEBGL) : "unknown";
    });
    if (/swiftshader/i.test(renderer) && process.env.SWIFTSHADER !== "1") console.warn("warning: software renderer", renderer);
    const png = await page.locator("canvas").screenshot({ omitBackground: true });
    const file = path.join(outDir, `${id}.webp`);
    await sharp(png).webp({ quality: 90, alphaQuality: 90, effort: 6, smartSubsample: true }).toFile(file);
    const bytes = fs.statSync(file).size;
    total += bytes;
    console.log(`${id.padEnd(14)} ${sizes[id].join("x").padEnd(8)} ${(bytes / 1024).toFixed(1)} KB  (${renderer})`);
    await page.close();
  }
} finally {
  await browser.close();
  await s.close();
}

const manifest = `// Generated by scripts/bake-sprites/bake.mjs. Do not edit by hand.
/** Pixel size [width, height] of each baked sprite in public/sprites/<legoId>.webp (2x). */
export const SPRITE_SIZES: Readonly<Record<string, readonly [number, number]>> = {
${Object.entries(sizes).map(([id, [w, h]]) => `  ${JSON.stringify(id)}: [${w}, ${h}],`).join("\n")}
};

/** Device pixel ratio the sprites were baked at. */
export const SPRITE_DPR = ${DPR};
`;
fs.writeFileSync(path.join(repo, "src/components/bricks/sprites.ts"), manifest);
const all = fs.readdirSync(outDir).filter((f) => f.endsWith(".webp")).reduce((a, f) => a + fs.statSync(path.join(outDir, f)).size, 0);
console.log(`baked ${only ? 1 : ids.length}; this run ${(total / 1024).toFixed(1)} KB; all sprites ${(all / 1024).toFixed(1)} KB`);
